#Text
str = "Hello World"
print(str)

#Numeric data types
int = 42
print(int)
float = 3.14
print(float)
complex = 1 + 2j
print(complex)

#Sequence data types
list = [1, 2, 3, 4, 5]
print(list)
tuple = (1, 2, 3, 4, 5)
print(tuple)
range = range(1, 10)
print(range)

#Mapping data type
dict = {"name": "Alice", "age": 30, "city": "New York"}
print(dict)

#Boolean data type
bool_true = True
print(bool_true)
bool_false = False
print(bool_false)

#None data type
none_value = None
print(none_value)